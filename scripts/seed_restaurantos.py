def tenant_id_for_email(email: str) -> str:
    """
    Resolve the tenant that owns a persona address, so an RLS-scoped statement can set the GUC.

    Needed because `auth_db.users` is `ENABLE` + **FORCE** ROW LEVEL SECURITY and `auth_user` is
    `NOSUPERUSER NOBYPASSRLS` — so a statement without the right tenant GUC sees no rows at all,
    including from psql. That is the correct posture, and it is worth contrasting with
    `pos_db`/`purchasing_db`, whose tables are NOT forced and whose owner therefore sees
    everything (see `seed_menu`).
    """
    domain = email.split("@")[-1]
    key = domain.split(".")[0]
    brand = next((s["brand"] for s in TENANTS if s["key"] == key), None)
    if not brand:
        die(f"'{email}' does not belong to any tenant this script seeds")
    row = sql("platform_db",
              f"SELECT id FROM tenants WHERE brand_name = '{brand}' ORDER BY created_at DESC LIMIT 1;")
    if not row:
        die(f"tenant '{brand}' does not exist — run --phase platform first")
    return row.splitlines()[0].strip()


def sql(database: str, statement: str) -> str:
    role = DB_ROLES[database]
    proc = subprocess.run(
        ["docker", "exec", "-i", PG_CONTAINER, "psql", "-U", role, "-d", database,
         "-v", "ON_ERROR_STOP=1", "-qtA"],
        input=statement, capture_output=True, text=True,
    )
    if proc.returncode != 0:
        die(f"psql ({role}@{database}) failed: {proc.stderr.strip()[:500]}")
    return proc.stdout.strip()


