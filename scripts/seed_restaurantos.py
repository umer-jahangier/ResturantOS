@dataclass
class Response:
    status: int
    body: Any
    raw: str

    def get(self, *path: str, default: Any = None) -> Any:
        node = self.body
        for key in path:
            if not isinstance(node, dict):
                return default
            node = node.get(key)
            if node is None:
                return default
        return node

    def data(self, *path: str, default: Any = None) -> Any:
        return self.get("data", *path, default=default)

    @property
    def error_code(self) -> str:
        return str(self.get("error", "code", default="") or self.get("code", default="") or "")

    def __str__(self) -> str:  # never carries a credential we put IN, but may carry one we got OUT
        return f"HTTP {self.status}"


_UNSAFE = ssl.create_default_context()
_UNSAFE.check_hostname = False
_UNSAFE.verify_mode = ssl.CERT_NONE


def request(
    method: str,
    path: str,
    token: str | None = None,
    body: Any = None,
    origin: str | None = None,
    retries: int = 6,
) -> Response:
    """
    One HTTP call, with the two retry behaviours this gateway genuinely requires.

    429 — RETRY WITH BACKOFF, NEVER A FAILURE. `platform-auth-route` is rate-limited at
    2/s (burst 100) and 13-13 recorded a script reporting "the SuperAdmin could not log in"
    seconds before a direct login answered 200. A seed that reports a fake failure is as bad
    as one that reports a fake success.

    503 SERVICE_UNAVAILABLE — retried once. This gateway's Resilience4j breaker answers the
    first request against a cold `lb://` pool with its own fallback body even though the
    backend is healthy. A SECOND consecutive 503 is returned as-is: this must never become a
    loop that hides a genuinely dead upstream.
    """
    url = (origin or GATEWAY).rstrip("/") + path
    payload = None if body is None else json.dumps(body).encode()
    delay = 0.75
    last: Response | None = None

    for attempt in range(retries):
        req = urllib.request.Request(url, data=payload, method=method)
        req.add_header("Accept", "application/json")
        if payload is not None:
            req.add_header("Content-Type", "application/json")
        if token:
            req.add_header("Authorization", f"Bearer {token}")

        try:
            with urllib.request.urlopen(req, timeout=90, context=_UNSAFE) as resp:
                raw = resp.read().decode("utf-8", "replace")
                status = resp.status
        except urllib.error.HTTPError as exc:
            raw = exc.read().decode("utf-8", "replace")
            status = exc.code
        except urllib.error.URLError as exc:
            if attempt == retries - 1:
                die(f"{method} {path}: cannot reach {url} — {exc.reason}. Is the gateway up?")
            time.sleep(delay)
            delay *= 2
            continue

        try:
            parsed = json.loads(raw) if raw.strip() else None
        except json.JSONDecodeError:
            parsed = None

        last = Response(status, parsed, raw)

        if status == 429:
            time.sleep(delay)
            delay = min(delay * 2, 20)
            continue
        if status == 503 and "SERVICE_UNAVAILABLE" in raw and attempt < 1:
            time.sleep(2)
            continue
        return last

    return last  # type: ignore[return-value]


def expect(resp: Response, *statuses: int, what: str) -> Response:
    if resp.status not in statuses:
        die(f"{what}: expected {' or '.join(map(str, statuses))}, got {resp.status} — {resp.raw[:600]}")
    return resp


