# PHASE 4 — the self-verification loop. THIS is the acceptance test for the whole phase.
# ════════════════════════════════════════════════════════════════════════════════════════════

def phase_verify(tenants: list[Tenant]) -> int:
    banner("PHASE 4 — VERIFICATION: every principal authenticates through the real gateway")
    print("  Not by inspecting the database for expected rows — a row is what a broken API")
    print("  leaves behind too. Every line below is a live login through ${GATEWAY}.")
    print()

    passed: list[str] = []
    failed: list[tuple[str, str]] = []

    def line(name: str, good: bool, detail: str) -> None:
        mark = f"{_GREEN}PASS{_RESET}" if good else f"{_RED}FAIL{_RESET}"
        print(f"  {mark}  {name:<34} {detail}")

    # ── the SuperAdmin ────────────────────────────────────────────────────────────────────
    resp = request("POST", "/api/v1/platform/auth/login",
                   body={"email": SUPERADMIN_EMAIL, "password": SUPERADMIN_PASSWORD})
    if resp.status == 200:
        claims = jwt_claims(resp.data("accessToken"))
        perms = claims.get("permissions") or []
        reach = request("GET", "/api/v1/platform/tenants?page=0&size=1",
                        token=resp.data("accessToken"))
        good = "SUPER_ADMIN" in (claims.get("roles") or []) and bool(perms) and reach.status != 403
        line(SUPERADMIN_EMAIL, good,
             f"roles={claims.get('roles')} permissions={len(perms)} "
             f"GET /api/v1/platform/tenants -> {reach.status}")
        (passed if good else failed).append(
            SUPERADMIN_EMAIL if good else (SUPERADMIN_EMAIL, "token or platform read was wrong"))  # type: ignore[arg-type]
    else:
        line(SUPERADMIN_EMAIL, False, f"login refused {resp.status} {resp.error_code}")
        failed.append((SUPERADMIN_EMAIL, f"login refused {resp.status} {resp.error_code}"))

    # ── all eighteen tenant personas ──────────────────────────────────────────────────────
    for t in tenants:
        print(f"  {_DIM}--- {t.brand} ({t.slug}) ---{_RESET}")
        for p in PERSONAS:
            email = persona_email(t.key, p["local"])
            password = persona_password(t.key, p["local"])
            token, note = login(email, password, t.slug)
            if not token:
                line(email, False, note)
                failed.append((email, note))
                continue
            claims = jwt_claims(token)
            roles = claims.get("roles") or []
            perms = claims.get("permissions") or []
            # The OWNER is verified first in every tenant, so its token is what resolves the HQ
            # branch the branch-scoped checks below need. A `--phase verify` run starts with no
            # branch at all, and a branch-scoped read without one is a 400 — which is "not 403"
            # and would therefore PASS while proving nothing about the caller's authority.
            if p["provisioned"] and not t.hq_branch_id:
                for b in request("GET", "/api/v1/branches", token=token).data(default=[]) or []:
                    if isinstance(b, dict) and b.get("isHq"):
                        t.hq_branch_id = b["id"]
            path = p["verify_path"].replace("{branch}", t.hq_branch_id or "")
            reach = request("GET", path, token=token)
            problems = []
            if p["role"] not in roles:
                problems.append(f"token carries roles {roles}, expected {p['role']}")
            if not perms:
                problems.append("token carries an EMPTY permission list")
            if reach.status == 403:
                problems.append(f"{path} answered 403 for a role that holds its gate")
            if reach.status >= 400 and reach.status != 403:
                problems.append(f"{path} answered {reach.status}, which is neither a refusal nor "
                                f"a result: {reach.raw[:120]}")
            if problems:
                line(email, False, "; ".join(problems))
                failed.append((email, "; ".join(problems)))
            else:
                line(email, True,
                     f"{p['role']:<14} {len(perms):>2} permissions  "
                     f"{p['verify_path'].split('?')[0]} -> {reach.status}")
                passed.append(email)

    print()
    print(f"  {_BOLD}{len(passed)} of {len(passed) + len(failed)} principals authenticated"
          f" and reached a role-appropriate endpoint.{_RESET}")
    if failed:
        print()
        print(f"  {_RED}{_BOLD}THE SEED IS NOT COMPLETE. A partial seed is a failed seed.{_RESET}")
        for email, why in failed:
            print(f"    {_RED}✗{_RESET} {email}: {why}")
        return 1
    print(f"  {_GREEN}Every seeded principal can log in. This is ROADMAP SC6's live evidence.{_RESET}")
    return 0


