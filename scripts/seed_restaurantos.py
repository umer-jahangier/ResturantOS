def reconcile_tenants() -> list[Tenant]:
    """Rebuild the tenant list from the platform API, for a run that starts mid-way."""
    out: list[Tenant] = []
    for spec in TENANTS:
        row = find_tenant_by_brand(spec["brand"])
        if not row:
            die(f"tenant '{spec['brand']}' does not exist. Run --phase platform first.")
        t = Tenant(key=spec["key"], brand=spec["brand"], tier=spec["tier"],
                   tenant_id=row.get("id") or row.get("tenantId"), slug=row.get("slug", ""),
                   admin_email=persona_email(spec["key"], "owner"), spec=spec)
        t.features = read_features(t.tenant_id)
        out.append(t)
    return out


def resolve_branches(tenants: list[Tenant], tokens: dict[str, str]) -> None:
    for t in tenants:
        token = tokens.get(t.admin_email)
        if not token:
            continue
        branches = request("GET", "/api/v1/branches", token=token).data(default=[]) or []
        hq = next((b for b in branches if isinstance(b, dict) and b.get("isHq")), None)
        if hq:
            t.hq_branch_id = hq["id"]
        t.branch_ids = [b["id"] for b in branches if isinstance(b, dict)]


def login_all(tenants: list[Tenant]) -> dict[str, str]:
    tokens: dict[str, str] = {}
    for t in tenants:
        for p in PERSONAS:
            email = persona_email(t.key, p["local"])
            token, _ = login(email, persona_password(t.key, p["local"]), t.slug)
            if token:
                tokens[email] = token
    return tokens


