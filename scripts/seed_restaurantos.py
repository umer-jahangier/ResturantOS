# TOTP (pure stdlib — T-13-15-SC forbids installing pyotp to make a seed run)
# ════════════════════════════════════════════════════════════════════════════════════════════

def totp_now(secret: str, skew: int = 0) -> str:
    key = base64.b32decode(secret + "=" * (-len(secret) % 8), casefold=True)
    counter = int(time.time()) // 30 + skew
    mac = hmac.new(key, struct.pack(">Q", counter), hashlib.sha1).digest()
    off = mac[-1] & 0x0F
    return str((struct.unpack(">I", mac[off:off + 4])[0] & 0x7FFFFFFF) % 10 ** 6).zfill(6)


def totp_secret_path(email: str) -> Path:
    return TOTP_DIR / re.sub(r"[^A-Za-z0-9._@-]", "_", email)


def load_totp_secret(email: str) -> str | None:
    p = totp_secret_path(email)
    return p.read_text().strip() if p.is_file() else None


def store_totp_secret(email: str, secret: str) -> None:
    TOTP_DIR.mkdir(parents=True, exist_ok=True)
    p = totp_secret_path(email)
    p.write_text(secret)
    os.chmod(p, 0o600)


