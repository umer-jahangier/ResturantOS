def jwt_claims(token: str) -> dict[str, Any]:
    seg = token.split(".")[1]
    seg += "=" * (-len(seg) % 4)
    return json.loads(base64.urlsafe_b64decode(seg))


class SuperAdmin:
    """
    ONE platform login, reused. `platform-auth-route` is rate-limited at 2/s and a seed that
    logs the SuperAdmin in per call will hit 429; the platform token is also short-lived and
    non-refreshable, so it is re-minted only when it is genuinely close to expiring.
    """

    def __init__(self) -> None:
        self._token: str | None = None
        self._expires_at: float = 0.0
        self.user_id: str | None = None

    def token(self) -> str:
        if self._token and time.time() < self._expires_at - 60:
            return self._token
        resp = request("POST", "/api/v1/platform/auth/login",
                       body={"email": SUPERADMIN_EMAIL, "password": SUPERADMIN_PASSWORD})
        if resp.status != 200:
            die(
                f"The project SuperAdmin '{SUPERADMIN_EMAIL}' could not log in through the gateway "
                f"(HTTP {resp.status}).\n"
                f"  This account is owned by a MIGRATION, not by this script — it is deliberately\n"
                f"  NOT re-created here, because a seeder that silently re-creates what a migration\n"
                f"  owns is how two sources of truth appear.\n"
                f"  Check {SUPERADMIN_MIGRATION} has run against platform_db, and that\n"
                f"  platform-admin-service and the gateway are both up.\n"
                f"  Response: {resp.raw[:400]}"
            )
        self._token = resp.data("accessToken")
        self.user_id = resp.data("platformUserId")
        self._expires_at = time.time() + float(resp.data("expiresIn", default=900) or 900)
        return self._token  # type: ignore[return-value]


SUPER = SuperAdmin()


def platform(method: str, path: str, body: Any = None) -> Response:
    return request(method, path, token=SUPER.token(), body=body)


def raw_login(email: str, password: str, slug: str, totp_code: str | None = None) -> Response:
    body: dict[str, Any] = {"email": email, "password": password, "tenantSlug": slug}
    if totp_code:
        body["totpCode"] = totp_code
    return request("POST", "/api/v1/auth/login", body=body)


def change_token_from(resp: Response) -> str | None:
    for detail in resp.get("error", "details", default=[]) or []:
        if isinstance(detail, dict) and detail.get("field") == "changeToken":
            return detail.get("issue")
    return None


def forced_change(change_token: str, current: str, new: str) -> Response:
    return request("POST", "/api/v1/auth/change-password/forced",
                   body={"changeToken": change_token, "currentPassword": current,
                         "newPassword": new})


def enrol_totp(email: str, password: str, slug: str, repair: bool = True) -> str | None:
    """
    Enrol a second factor over the PUBLIC bootstrap endpoints — 13-06's and 13-13's recipe,
    copied rather than reinvented.

    ORDER MATTERS and is not negotiable: the forced password change happens FIRST, enrolment
    second, so the factor is never bound under a temporary credential that whoever provisioned
    the account also knows.

    Returns None rather than aborting when enrolment genuinely cannot proceed, so ONE persona in
    an odd state does not take the other seventeen down with it. Measured: a run died outright on
    `409 TOTP_ALREADY_ENROLLED` for a single address and reported nothing about anybody else.

    That 409 beside a `401 TOTP_ENROLLMENT_REQUIRED` from login is not a contradiction — the two
    endpoints read different columns. Login demands enrolment when `totp_secret IS NULL`;
    bootstrap refuses when `totp_enabled` is true. An account with the flag set and no secret is
    stuck between them and can never log in again, because no endpoint at any tier resets another
    user's second factor. The repair clears the factor directly and re-enrols, and prints that
    write in the ledger.
    """
    resp = request("POST", "/api/v1/auth/2fa/bootstrap",
                   body={"email": email, "password": password, "tenantSlug": slug})

    if resp.status == 409 and "TOTP_ALREADY_ENROLLED" in resp.raw:
        if not repair:
            warn(f"{email}: already holds a factor this run has no secret for, and repair is off")
            return None
        warn(f"{email}: holds an enrolled factor this run has no secret for — clearing and re-enrolling")
        clear_totp(email)
        resp = request("POST", "/api/v1/auth/2fa/bootstrap",
                       body={"email": email, "password": password, "tenantSlug": slug})

    uri = resp.data("otpauthUri")
    if not uri:
        warn(f"TOTP bootstrap for {email} returned no otpauth uri (HTTP {resp.status}): {resp.raw[:200]}")
        return None
    secret = urllib.parse.parse_qs(urllib.parse.urlparse(uri).query)["secret"][0]
    verify = request("POST", "/api/v1/auth/2fa/bootstrap/verify",
                     body={"email": email, "password": password, "tenantSlug": slug,
                           "code": totp_now(secret)})
    if verify.status != 200:
        warn(f"TOTP enrolment for {email} was not accepted (HTTP {verify.status}): {verify.raw[:200]}")
        return None
    store_totp_secret(email, secret)
    return secret


def login(email: str, password: str, slug: str) -> tuple[str | None, str]:
    """
    Log a persona in, meeting whichever gates the platform raises, and return
    (access_token, note). A None token means the persona could not authenticate; the note
    always says why in terms a reader can act on.

    Both gates a provisioned or created account can meet are handled here, in the order
    13-08 pinned:  403 PASSWORD_CHANGE_REQUIRED  then  401 TOTP_ENROLLMENT_REQUIRED.
    """
    secret = load_totp_secret(email)
    resp = raw_login(email, password, slug, totp_now(secret) if secret else None)

    if resp.status == 200:
        return resp.data("accessToken"), "ok"

    if resp.status == 401 and resp.error_code == "TOTP_ENROLLMENT_REQUIRED":
        enrol_totp(email, password, slug)
        secret = load_totp_secret(email)
        resp = raw_login(email, password, slug, totp_now(secret) if secret else None)
        if resp.status == 200:
            return resp.data("accessToken"), "ok (enrolled a second factor)"
        return None, f"still refused after TOTP enrolment: {resp.status} {resp.error_code}"

    if resp.status == 401 and resp.error_code == "TOTP_REQUIRED":
        if not secret:
            # The factor is enrolled and this run holds no secret for it. The secret is minted by
            # auth-service and cannot be re-derived, and no endpoint at any tier revokes another
            # user's second factor — so the only way back is to clear it and enrol again, which is
            # an enumerated direct write rather than a silent one.
            if enrol_totp(email, password, slug):
                secret = load_totp_secret(email)
                resp = raw_login(email, password, slug, totp_now(secret) if secret else None)
                if resp.status == 200:
                    return resp.data("accessToken"), "ok (factor re-enrolled)"
            return None, (
                "requires a TOTP code and this run holds no secret for it, and re-enrolment did "
                f"not succeed. Secrets live in {TOTP_DIR}; losing that directory is recoverable "
                "but not free."
            )
        # One clock-skew retry before calling it a failure.
        resp = raw_login(email, password, slug, totp_now(secret, skew=-1))
        if resp.status == 200:
            return resp.data("accessToken"), "ok (previous TOTP window)"
        return None, f"TOTP code refused: {resp.status} {resp.error_code}"

    if resp.status == 403 and resp.error_code == "PASSWORD_CHANGE_REQUIRED":
        return None, "still carries an outstanding forced-change flag"

    return None, f"{resp.status} {resp.error_code or resp.raw[:120]}"


