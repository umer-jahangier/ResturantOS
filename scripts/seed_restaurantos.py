def seed_menu(t: Tenant, manager_token: str) -> list[str]:
    """
    Menu categories and items, created by the MANAGER — the role that holds pos.menu.manage.
    An owner-driven seed proves nothing about the other five roles.

    🔴 THE LOOKUP IS DELIBERATELY NOT BY NAME, and the reason is a live defect this script
    found. `GET /api/v1/pos/menu/items/admin` and `.../categories/admin` return EVERY TENANT'S
    rows: `MenuItemRepository`'s queries carry no tenant predicate and rely entirely on row-level
    security, but `pos_db.menu_items` is `relrowsecurity=t, relforcerowsecurity=f` and the
    runtime connects as `pos_user`, which OWNS the table — so the policy does not apply to it.

    Measured, not inferred: the Saffron manager (tenant 4f2783b6…) sees 13 items of which 2 are
    its own, including another tenant's "Beef Nihari".

    A name-keyed reconciliation against that list adopts a NEIGHBOUR'S menu item id, and the
    order priced from it is then rejected — which is exactly how this run found the defect.
    Every lookup here is therefore keyed on a description this script writes and that contains
    the tenant's brand, so a collision across tenants is impossible. The defect itself is
    pos-service's and is recorded in the phase's deferred items; it is NOT worked around
    silently.
    """
    wanted = t.spec["menu_items"]
    item_ids: list[str] = []

    def mine(rows: Iterable[Any], marker: str) -> dict[str, str]:
        out: dict[str, str] = {}
        for row in rows or []:
            if isinstance(row, dict) and (row.get("description") or "").endswith(marker):
                out[row.get("name") or ""] = row["id"]
        return out

    # The marker carries the TENANT ID, not just the brand. A brand is stable across a delete
    # and re-provision, and nothing purges pos_db when a tenant goes away (tenant deletion is a
    # status flip — 13-CONTEXT's deferred list), so a brand-only marker adopts a dead tenant's
    # rows. The display NAME is left clean; only the description carries it.
    marker = f"— {t.brand} · tenant {t.tenant_id[:8]}"
    cats = request("GET", "/api/v1/pos/menu/categories/admin", token=manager_token)
    own_categories = mine(cats.data(default=[]) if cats.status == 200 else [], marker)
    items = request("GET", "/api/v1/pos/menu/items/admin", token=manager_token)
    own_items = mine(items.data(default=[]) if items.status == 200 else [], marker)

    for order, (cat_name, entries) in enumerate(MENU):
        if len(item_ids) >= wanted:
            break
        cat_id = own_categories.get(cat_name)
        if not cat_id:
            resp = request("POST", "/api/v1/pos/menu/categories", token=manager_token,
                           body={"name": cat_name, "description": f"{cat_name} {marker}",
                                 "sortOrder": order})
            if resp.status not in (200, 201):
                warn(f"{t.slug}: menu category '{cat_name}' answered {resp.status} — {resp.raw[:180]}")
                continue
            cat_id = resp.data("id")
            own_categories[cat_name] = cat_id
        for name, price, tax in entries:
            if len(item_ids) >= wanted:
                break
            if name in own_items:
                item_ids.append(own_items[name])
                continue
            resp = request("POST", "/api/v1/pos/menu/items", token=manager_token,
                           body={"categoryId": cat_id, "name": name,
                                 "description": f"{name} {marker}",
                                 "basePricePaisa": price, "taxRatePct": tax})
            if resp.status not in (200, 201):
                warn(f"{t.slug}: menu item '{name}' answered {resp.status} — {resp.raw[:180]}")
                continue
            item_ids.append(resp.data("id"))
    if item_ids:
        ok(f"{t.slug}: menu has {len(item_ids)} items across {len(own_categories)} categories "
           f"(created by the MANAGER, pos.menu.manage)")
    return item_ids


def seed_inventory(t: Tenant, manager_token: str, menu_item_ids: list[str]) -> int:
    """Ingredients and a recipe, so depletion has something to deplete. MANAGER holds
    inventory.item.manage."""
    made = 0
    # The standard unit set is PROVISIONED per tenant by inventory-service's own
    # UomProvisioningService (StandardUomCatalog: G/KG/MG/LB/OZ, ML/L/…, EACH/DOZEN/PAIR).
    # This script therefore READS the codes rather than inventing them — creating "kg" beside a
    # provisioned "KG" would give the tenant two units for one thing, which is precisely the
    # duplicate-master-data problem the provisioning service exists to prevent.
    uoms = request("GET", "/api/v1/inventory/uom", token=manager_token)
    if uoms.status in (403, 503):
        GAPS.append(f"{t.slug}: inventory answered {uoms.status} for the MANAGER — no ingredients "
                    f"or recipes were seeded")
        return 0
    have_uom = {(u.get("code") or "").upper() for u in (uoms.data(default=[]) or [])
                if isinstance(u, dict)}
    stock_uom = "KG" if "KG" in have_uom else next(iter(sorted(have_uom)), None)
    if not stock_uom:
        GAPS.append(f"{t.slug}: the tenant has no units of measure — inventory-service's "
                    f"UomProvisioningService did not run for it")
        return 0

    cats = request("GET", "/api/v1/inventory/categories", token=manager_token)
    cat_id = None
    for row in (cats.data(default=[]) or []) if cats.status == 200 else []:
        if isinstance(row, dict) and row.get("name") == "Raw Materials":
            cat_id = row["id"]
    if not cat_id:
        r = request("POST", "/api/v1/inventory/categories", token=manager_token,
                    body={"name": "Raw Materials", "code": "RAW", "sortOrder": 1})
        if r.status in (200, 201):
            cat_id = r.data("id")
        else:
            GAPS.append(f"{t.slug}: inventory category create answered {r.status}")
            return 0

    existing = request("GET", "/api/v1/inventory/ingredients", token=manager_token)
    have = {i.get("sku") for i in (existing.data(default=[]) or []) if isinstance(i, dict)}
    ingredient_ids: list[str] = []
    for sku, name in (("CHK-001", "Chicken"), ("RIC-001", "Basmati Rice"), ("SPC-001", "Spice Mix")):
        if sku in have:
            for i in existing.data(default=[]) or []:
                if isinstance(i, dict) and i.get("sku") == sku:
                    ingredient_ids.append(i["id"])
            continue
        r = request("POST", "/api/v1/inventory/ingredients", token=manager_token,
                    body={"name": name, "sku": sku, "baseUomCode": stock_uom, "categoryId": cat_id,
                          "reorderPoint": 5, "parLevel": 25, "perishable": True,
                          "shelfLifeDays": 7})
        if r.status in (200, 201):
            ingredient_ids.append(r.data("id"))
            made += 1
        else:
            warn(f"{t.slug}: ingredient '{sku}' answered {r.status} — {r.raw[:160]}")

    if ingredient_ids and menu_item_ids:
        # inventory-service holds its own PROJECTION of the POS menu, fed by an event. A menu
        # item created moments ago is not there yet, and a recipe against it answers 404
        # MENU_ITEM_NOT_FOUND. That is eventual consistency working correctly, not a defect —
        # so this waits for the projection instead of reporting a false gap.
        r = None
        for _ in range(10):
            r = request("POST", "/api/v1/inventory/recipes", token=manager_token,
                        body={"menuItemId": menu_item_ids[0], "yieldServings": 1,
                              "name": "Seed recipe",
                              "lines": [{"ingredientId": ingredient_ids[0], "qty": 0.25,
                                         "uomCode": stock_uom, "yieldPct": 100}]})
            if r.status != 404:
                break
            time.sleep(2)
        if r is not None and r.status in (200, 201):
            ok(f"{t.slug}: {len(ingredient_ids)} ingredients and a recipe "
               f"(depletion has something to deplete)")
        else:
            GAPS.append(f"{t.slug}: recipe create answered {r.status} ({r.error_code}) after "
                        f"waiting for the menu projection — the ingredient set is seeded, "
                        f"the recipe is not")
    elif ingredient_ids:
        ok(f"{t.slug}: {len(ingredient_ids)} ingredients")
    return made


def seed_purchasing(t: Tenant, manager_token: str) -> int:
    """Vendor -> PO -> approve -> send -> goods receipt -> invoice, by the MANAGER (vendor.*).

    Invoice dates are spread over several BUSINESS DATES through the real API field, which is
    how period-scoped purchase reporting gets more than one day in it without any direct write:
    `invoiceDate` is a request field, so no back-dating is needed anywhere."""
    vendor_name = f"{t.brand} Supplies"
    # 🔴 `GET /api/v1/purchasing/vendors` returns EVERY TENANT'S vendors, for the same reason
    # the POS menu listing does: `purchasing_db.vendors` is `relrowsecurity=t
    # relforcerowsecurity=f` and the runtime connects as `purchasing_user`, which OWNS the
    # table, so the policy never applies to it. The write path IS tenant-scoped, so adopting a
    # neighbour's vendor id produces `404 Vendor not found` on the very next call — which is
    # how this run found it. The reconciliation key is therefore a `notes` marker carrying this
    # tenant's id, which no other tenant's row can carry.
    marker = f"seed:{t.tenant_id}"
    listed = request("GET", "/api/v1/purchasing/vendors", token=manager_token)
    if listed.status in (403, 404, 503):
        GAPS.append(f"{t.slug}: purchasing answered {listed.status} for the MANAGER — "
                    f"no vendor, purchase order or goods receipt was seeded")
        return 0
    vendor_id = None
    rows = listed.data(default=[]) or []
    if isinstance(rows, dict):
        rows = rows.get("content") or []
    for row in rows:
        if isinstance(row, dict) and (row.get("notes") or "") == marker:
            vendor_id = row["id"]
    if not vendor_id:
        r = request("POST", "/api/v1/purchasing/vendors", token=manager_token,
                    body={"name": vendor_name, "paymentTerms": "NET_30", "notes": marker,
                          "ntn": "1234567-8", "strn": "12-34-5678-901-23"})
        if r.status not in (200, 201):
            GAPS.append(f"{t.slug}: vendor create answered {r.status} — {r.raw[:160]}")
            return 0
        vendor_id = r.data("id")

    import datetime as _dt
    today = _dt.date.today()
    made = 0
    for n in range(t.spec["invoices"]):
        # Tenant-qualified for the same reason every other key here is: a vendor invoice number
        # collides across a delete-and-reprovision otherwise.
        invoice_no = f"SEED-{t.key.upper()}-{t.tenant_id[:8].upper()}-{n + 1}"
        invoice_date = today - _dt.timedelta(days=n * 3)
        ingredient = det(t.tenant_id, "po-ingredient", str(n))
        qty, unit = 10 + n * 5, 100000
        po = request("POST", "/api/v1/purchasing/purchase-orders", token=manager_token,
                     body={"vendorId": vendor_id, "branchId": t.hq_branch_id,
                           "notes": f"seed {invoice_no}",
                           "lines": [{"ingredientId": ingredient, "qty": qty, "uom": "kg",
                                      "unitPricePaisa": unit}]})
        if po.status not in (200, 201):
            if po.status == 409:
                made += 1  # already there from a previous run
                continue
            warn(f"{t.slug}: purchase order {invoice_no} answered {po.status} — {po.raw[:160]}")
            continue
        po_id, line_id = po.data("id"), (po.data("lines", default=[{}]) or [{}])[0].get("id")
        for verb, body in (("submit", None), ("approve", {}), ("send", None)):
            request("POST", f"/api/v1/purchasing/purchase-orders/{po_id}/{verb}",
                    token=manager_token, body=body)
        request("POST", f"/api/v1/purchasing/purchase-orders/{po_id}/mock-receive",
                token=manager_token, body={"lines": [{"poLineId": line_id, "receivedQty": qty}]})
        inv = request("POST", "/api/v1/purchasing/invoices", token=manager_token,
                      body={"purchaseOrderId": po_id, "invoiceNo": invoice_no,
                            "invoiceDate": invoice_date.isoformat(),
                            "inputTaxPaisa": 1500 * (n + 1),
                            "lines": [{"poLineId": line_id, "qty": qty, "unitPricePaisa": unit}]})
        if inv.status in (200, 201):
            made += 1
        elif inv.status == 409:
            made += 1
        else:
            warn(f"{t.slug}: invoice {invoice_no} answered {inv.status} — {inv.raw[:160]}")
    if made:
        ok(f"{t.slug}: {made} vendor invoice(s) matched through PO → approve → send → GRN → invoice, "
           f"dated across {t.spec['invoices']} business date(s)")
    return made


def seed_pos(t: Tenant, waiter_token: str, cashier_token: str, menu_item_ids: list[str]) -> int:
    """
    The point of D-30, driven exactly as the roles intend it:

      the WAITER  creates the order, adds lines, fires it to the KDS and serves — with NO till,
                  because a waiter cannot open one and that is the whole point;
      the CASHIER settles it. A CASH tender requires the PAYING user to hold an OPEN till, so
                  the cashier opens one first. A CARD tender needs none, and some orders are
                  settled that way deliberately so the exemption is exercised too.
    """
    if not menu_item_ids:
        GAPS.append(f"{t.slug}: no menu items, so no point-of-sale orders were seeded")
        return 0

    # The cashier's own open session, asked for the way the active-till bar asks: no branchId,
    # status filtered at the producer. Passing branchId switches this endpoint to the paginated
    # admin history instead, which is a different question and answered a different way.
    till = request("GET", "/api/v1/pos/tills?status=OPEN", token=cashier_token)
    rows = (till.data(default=[]) or []) if till.status == 200 else []
    if isinstance(rows, dict):
        rows = rows.get("content") or []
    open_till = next((r["id"] for r in rows
                      if isinstance(r, dict) and (r.get("status") or "OPEN") == "OPEN"), None)
    if open_till:
        step(f"{t.slug}: the CASHIER already holds an open till")
    else:
        r = request("POST", "/api/v1/pos/tills", token=cashier_token,
                    body={"branchId": t.hq_branch_id, "openingFloatPaisa": 500000})
        if r.status in (200, 201):
            open_till = r.data("id")
            ok(f"{t.slug}: the CASHIER opened a till "
               f"(a CASH settlement is 409 NO_OPEN_TILL without one — D-30)")
        elif r.status == 409 and "TILL_ALREADY_OPEN" in r.raw:
            open_till = "already-open"
            step(f"{t.slug}: the CASHIER already holds an open till")
        else:
            warn(f"{t.slug}: the cashier could not open a till ({r.status}) — "
                 f"cash settlements will be refused: {r.raw[:180]}")

    closed = 0
    for n in range(t.spec["orders"]):
        client_order_id = det(t.tenant_id, "order", str(n))
        created = request("POST", "/api/v1/pos/orders", token=waiter_token,
                          body={"branchId": t.hq_branch_id, "clientOrderId": client_order_id,
                                "type": "DINE_IN", "coverCount": 2 + (n % 3)})
        if created.status not in (200, 201):
            warn(f"{t.slug}: order {n} create answered {created.status} — {created.raw[:180]}")
            continue
        order_id = created.data("id")
        # createOrder is IDEMPOTENT on clientOrderId (OrderServiceImpl:145), and clientOrderId is
        # a uuid5 over a stable name — so a second run gets the same order back rather than a
        # second one. Lines are added only when it has none, or a re-run would keep growing it.
        already_built = bool(created.data("items", default=[]) or [])

        for k in range(0 if already_built else 1 + (n % 2)):
            item = menu_item_ids[(n + k) % len(menu_item_ids)]
            added = request("POST", f"/api/v1/pos/orders/{order_id}/items", token=waiter_token,
                            body={"menuItemId": item, "branchId": t.hq_branch_id,
                                  "quantity": 1 + (k % 2)})
            if added.status not in (200, 201):
                # Checked rather than fired and forgotten: an unchecked add is how a run reports
                # "order has a zero total" and leaves the reader guessing which call failed.
                warn(f"{t.slug}: order {n} line {k} answered {added.status} — {added.raw[:180]}")
        if not already_built:
            request("POST", f"/api/v1/pos/orders/{order_id}/send-to-kds", token=waiter_token)

        # `branchId` is a REQUIRED query parameter on the single-order read. Omitting it is a
        # 400, and a 400 read is how a run reports "the order has a zero total" and blames the
        # settlement for a defect in the fetch — which is exactly what happened here once.
        one = f"/api/v1/pos/orders/{order_id}?branchId={t.hq_branch_id}"
        current = request("GET", one, token=waiter_token)
        if current.status != 200:
            warn(f"{t.slug}: order {n} could not be read back ({current.status}) — {current.raw[:180]}")
            continue
        for lineitem in current.data("items", default=[]) or []:
            served = request("POST", f"/api/v1/pos/orders/{order_id}/items/{lineitem['id']}/serve",
                             token=waiter_token)
            if served.status not in (200, 201, 409):
                warn(f"{t.slug}: order {n} serve answered {served.status} — {served.raw[:160]}")

        settled = request("GET", one, token=cashier_token)
        total = int(settled.data("totalPaisa", default=0) or 0)
        # An order a previous run already settled comes back CLOSED. `OrderDto` carries no
        # amountPaidPaisa — that field is on the SUMMARY projection — so the status is what says
        # "already settled"; asking for a tender again is a 409 STATE_INVALID, which is the API
        # being right and the seed being wrong.
        if (settled.data("status") or "") == "CLOSED":
            closed += 1
            continue
        if total <= 0:
            warn(f"{t.slug}: order {n} has a zero total — not settling it")
            continue
        # An order auto-closes once it is fully PAID and fully SERVED; POST /{id}/close is
        # retired to 410 Gone (POS-23) and is deliberately not called.
        method = "CARD" if n % 3 == 2 else "CASH"
        pay = request("POST", f"/api/v1/pos/orders/{order_id}/payments", token=cashier_token,
                      body={"method": method, "amountPaisa": total, "tenderedPaisa": total,
                            "referenceNo": f"SEED-{n}" if method == "CARD" else None})
        if pay.status in (200, 201):
            closed += 1
        elif pay.status == 409 and "NO_OPEN_TILL" in pay.raw:
            die(f"{t.slug}: a CASH settlement was refused 409 NO_OPEN_TILL. The cashier holds no "
                f"open till — that is D-30 working exactly as specified, and the seed's fault.")
        else:
            warn(f"{t.slug}: order {n} {method} payment answered {pay.status} — {pay.raw[:180]}")
    if closed:
        ok(f"{t.slug}: {closed} orders taken by the WAITER (no till) and settled by the CASHIER "
           f"across CASH and CARD tenders")
    return closed


def phase_business(tenants: list[Tenant], tokens: dict[str, str]) -> None:
    banner("PHASE 3 — catalog, purchasing and point-of-sale data, by the role that owns each")

    for t in tenants:
        print()
        print(f"  {_BOLD}{t.brand} ({t.slug}){_RESET}")
        mgr = tokens.get(persona_email(t.key, "manager"))
        waiter = tokens.get(persona_email(t.key, "waiter"))
        cashier = tokens.get(persona_email(t.key, "cashier"))
        if not (mgr and waiter and cashier):
            die(f"{t.slug}: phase 3 needs manager, waiter and cashier tokens from phase 2.")

        items = seed_menu(t, mgr)
        seed_inventory(t, mgr, items)
        seed_purchasing(t, mgr)
        seed_pos(t, waiter, cashier, items)

    # Non-emptiness, asserted for a ROLE-APPROPRIATE persona rather than for the owner.
    print()
    step("checking each tenant's dashboards and reports are non-empty for the right persona")
    import datetime as _dt
    frm = (_dt.date.today() - _dt.timedelta(days=30)).isoformat()
    to = _dt.date.today().isoformat()
    for t in tenants:
        acct = tokens.get(persona_email(t.key, "accountant"))
        mgr = tokens.get(persona_email(t.key, "manager"))
        coa = request("GET", "/api/v1/finance/accounts?page=0&size=5", token=acct)
        n_coa = len(coa.data(default=[]) or []) if coa.status == 200 else 0
        # `status` must be given explicitly: the default listing is the POS floor view, which
        # deliberately excludes CLOSED orders. Counting settled orders without it reports zero
        # for a tenant whose orders all settled — the opposite of what is being asked.
        orders = request("GET",
                         f"/api/v1/pos/orders?branchId={t.hq_branch_id}&status=CLOSED&size=100",
                         token=mgr)
        raw_orders = orders.data(default=[]) or []
        if isinstance(raw_orders, dict):
            raw_orders = raw_orders.get("content") or []
        n_orders = len(raw_orders)
        rep = request("POST", "/api/v1/reporting/reports/sales-by-day/run", token=acct,
                      body={"from": frm, "to": to, "branchId": t.hq_branch_id})
        n_rows = 0
        if rep.status == 200:
            payload = rep.data(default={}) or {}
            n_rows = (len(payload.get("rows") or payload.get("data") or [])
                      if isinstance(payload, dict) else len(payload))
        tiles = request("GET", f"/api/v1/reporting/dashboard/{t.hq_branch_id}/tiles", token=acct)
        n_tiles = len(tiles.data(default={}) or {}) if tiles.status == 200 else 0
        print(f"     {t.slug:<18} chart-of-accounts {n_coa:>3}   settled orders {n_orders:>3}   "
              f"sales-by-day rows {n_rows:>3}   dashboard tiles {n_tiles:>3} ({tiles.status})")
        if n_orders == 0:
            GAPS.append(f"{t.slug}: no SETTLED orders are visible to the MANAGER — "
                        f"dashboards and sales reports will be empty")
        if n_rows == 0:
            GAPS.append(f"{t.slug}: sales-by-day returned no rows for the last 30 days")


