def read_features(tenant_id: str) -> dict[str, bool]:
    resp = expect(platform("GET", f"/api/v1/platform/tenants/{tenant_id}/features"), 200,
                  what="reading tenant features")
    raw = resp.data("features", default=None)
    if raw is None:
        raw = resp.data(default={})
    if isinstance(raw, dict):
        return {k: bool(v) for k, v in raw.items()}
    out: dict[str, bool] = {}
    for row in raw or []:
        if isinstance(row, dict):
            code = row.get("featureCode") or row.get("code")
            if code:
                out[code] = bool(row.get("enabled", row.get("isEnabled")))
    return out


def phase_platform() -> list[Tenant]:
    banner("PHASE 1 — the platform, and three deliberately divergent tenants")

    step(f"verifying the SuperAdmin by LOGGING IN as {SUPERADMIN_EMAIL} (not by inserting it)")
    claims = jwt_claims(SUPER.token())
    if "SUPER_ADMIN" not in (claims.get("roles") or []):
        die(f"the SuperAdmin token does not carry the SUPER_ADMIN role: {claims.get('roles')}")
    ok(f"SuperAdmin authenticated through the real gateway — platformUserId {SUPER.user_id}")

    tenants: list[Tenant] = []
    for spec in TENANTS:
        t = Tenant(key=spec["key"], brand=spec["brand"], tier=spec["tier"], spec=spec)
        t.admin_email = persona_email(t.key, "owner")

        existing = find_tenant_by_brand(t.brand)
        if existing:
            t.tenant_id = existing["id"] if "id" in existing else existing.get("tenantId", "")
            t.slug = existing.get("slug", "")
            step(f"{t.brand}: already provisioned as '{t.slug}' — reconciling, not duplicating")
            if (existing.get("tier") or "").upper() != t.tier:
                resp = platform("POST", f"/api/v1/platform/tenants/{t.tenant_id}/tier",
                                body={"tier": t.tier, "force": True})
                expect(resp, 200, what=f"setting {t.brand} to tier {t.tier}")
                ok(f"{t.brand}: tier reconciled to {t.tier}")
        else:
            step(f"{t.brand}: provisioning through POST /api/v1/platform/tenants (tier {t.tier})")
            resp = platform("POST", "/api/v1/platform/tenants",
                            body={"brandName": t.brand, "adminEmail": t.admin_email, "tier": t.tier})
            expect(resp, 201, 200, what=f"provisioning {t.brand}")
            t.tenant_id = resp.data("tenantId")
            t.slug = resp.data("slug")
            t.admin_temp_password = resp.data("tempPassword")
            ok(f"{t.brand}: tenant {t.slug} provisioned, admin {t.admin_email}")

        if not t.tenant_id or not t.slug:
            die(f"{t.brand}: could not establish a tenant id and slug")

        # Diverge the module sets DELIBERATELY, on top of the tier difference.
        for code, enabled in spec["overrides"]:
            resp = platform("PATCH", f"/api/v1/platform/tenants/{t.tenant_id}/features/{code}",
                            body={"enabled": enabled})
            expect(resp, 200, what=f"setting {code}={enabled} on {t.brand}")
            ok(f"{t.brand}: {code} forced {'ON' if enabled else 'OFF'} (an explicit override, not a tier default)")

        t.features = read_features(t.tenant_id)
        enabled = sorted(c for c, v in t.features.items() if v)
        step(f"{t.brand} [{t.tier}] enables {len(enabled)} features: {', '.join(enabled)}")
        tenants.append(t)

    # ASSERT the divergence rather than trusting the calls succeeded. Three tenants whose
    # enabled sets are equal would mean feature gating is assumed, which is the exact thing
    # 13-CONTEXT says must not happen.
    sets = {t.key: frozenset(c for c, v in t.features.items() if v) for t in tenants}
    keys = list(sets)
    for i in range(len(keys)):
        for j in range(i + 1, len(keys)):
            a, b = keys[i], keys[j]
            if sets[a] == sets[b]:
                die(
                    f"tenants '{a}' and '{b}' ended with IDENTICAL enabled module sets. "
                    f"Feature gating would be assumed rather than exercised, which is the "
                    f"prohibition this phase exists to close."
                )
    ok(f"all {len(TENANTS)} enabled module sets are pairwise DIFFERENT — asserted, not assumed")
    for i in range(len(keys)):
        for j in range(i + 1, len(keys)):
            a, b = keys[i], keys[j]
            only_a = sorted(sets[a] - sets[b])
            only_b = sorted(sets[b] - sets[a])
            print(f"     {a} ⊖ {b}: only {a} = {only_a or '—'} ; only {b} = {only_b or '—'}")

    return tenants


