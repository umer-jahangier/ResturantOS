# ── 4. The audit trail — read out of the outbox, not out of a response ──────────────────────

echo "--- the audit event, read from event_outbox on the enforcing database ---"

# Read the envelope of the most recent admin reset for tenant B — the PLATFORM one, where the actor
# and the target are unambiguously different PEOPLE in different id spaces.
AUDIT_B="$(printf '%s\n' "
  SELECT set_config('app.current_tenant_id', '${TENANT_B_ID}', false);
  SELECT envelope_json FROM event_outbox
   WHERE event_type = 'ADMIN_PASSWORD_RESET' AND tenant_id = '${TENANT_B_ID}'
   ORDER BY created_at DESC LIMIT 1;
" | auth_sql 2>/dev/null | tail -1)"

if [[ -z "$AUDIT_B" ]]; then
  fail "no ADMIN_PASSWORD_RESET row in event_outbox — the audit write did not commit. 13-14 found an"
  echo "      impersonation audit that could never commit at all while the method reported success."
else
  pass "the reset wrote a PERSISTED audit row (not merely called a publisher)"
  AUDIT_FIELDS="$(printf '%s' "$AUDIT_B" | python3 -c "
import sys, json
p = json.load(sys.stdin)['payload']
print(p.get('actingAdministratorId',''))
print(p.get('targetUserId',''))
print(p.get('actorTier',''))
print(p.get('reason',''))
print(json.dumps(p))
")"
  AUDIT_ACTOR="$(printf  '%s' "$AUDIT_FIELDS" | sed -n 1p)"
  AUDIT_TARGET="$(printf '%s' "$AUDIT_FIELDS" | sed -n 2p)"
  AUDIT_TIER="$(printf   '%s' "$AUDIT_FIELDS" | sed -n 3p)"
  AUDIT_REASON="$(printf '%s' "$AUDIT_FIELDS" | sed -n 4p)"
  AUDIT_PAYLOAD="$(printf '%s' "$AUDIT_FIELDS" | sed -n 5p)"

  assert_status "$OWNER_B_ID" "$AUDIT_TARGET" "the audit row names the TARGET whose password changed"
  if [[ -n "$AUDIT_ACTOR" && "$AUDIT_ACTOR" != "$AUDIT_TARGET" ]]; then
    pass "the acting administrator and the target are DIFFERENT values (${AUDIT_ACTOR} vs ${AUDIT_TARGET})"
  else
    fail "the audit row names the target as its own actor — the impersonation defect, repeated"
  fi
  assert_status 'PLATFORM' "$AUDIT_TIER" "the row says which tier acted, so the two id spaces are separable"
  assert_contains "$AUDIT_REASON" 'support ticket 4711' "the reason the operator gave is recorded verbatim"

  # No credential material anywhere in the payload, checked by VALUE. A key-set check passes against
  # a payload that republishes the password under a harmless name — 13-09 falsified exactly that.
  if printf '%s' "$AUDIT_PAYLOAD" | grep -qF -- "$OWNER_B_RESET_TEMP"; then
    fail "the audit payload contains the temporary password — event_outbox is durable and replicated"
  else
    pass "the audit payload contains no password material at all"
  fi
  if printf '%s' "$AUDIT_PAYLOAD" | grep -qF -- "$OWNER_B_FINAL_PASSWORD"; then
    fail "the audit payload contains the user's chosen password"
  else
    pass "nor the password the user subsequently chose"
  fi
fi

# The tenant tier writes its own row, in its own tenant, naming its own actor.
AUDIT_A_ACTOR="$(printf '%s\n' "
  SELECT set_config('app.current_tenant_id', '${TENANT_A_ID}', false);
  SELECT envelope_json FROM event_outbox
   WHERE event_type = 'ADMIN_PASSWORD_RESET' AND tenant_id = '${TENANT_A_ID}'
