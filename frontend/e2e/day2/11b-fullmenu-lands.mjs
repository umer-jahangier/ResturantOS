/* Does the Full Menu add land on the SAME check, as a revision? */
import { newBrowser, newPage, go, shot, saveState, loadState, log, BASE, apiGet } from "./lib.mjs";
const S = loadState(); const NEW = S.newCashier; const ORD = S.routingProof.ord;
const browser = await newBrowser(); const cash = await newPage(browser);
await cash.goto(`${BASE}/login`, { waitUntil: "domcontentloaded" }); await cash.waitForTimeout(1400);
const sl = cash.locator('input[name="tenantSlug"], input#tenantSlug'); if (await sl.count()) await sl.first().fill(NEW.slug);
await cash.locator('input[name="email"]').first().fill(NEW.email);
await cash.locator('input[name="password"]').first().fill(NEW.newPassword);
await cash.locator('button[type="submit"]').first().click(); await cash.waitForTimeout(6000);
await go(cash, "/app/pos", { waitMs: 8000 });
await cash.getByText("Order Management", { exact: true }).first().click(); await cash.waitForTimeout(4000);
await cash.locator('input[placeholder*="Search" i], input[type=search]').last().fill(ORD); await cash.waitForTimeout(3000);
await cash.locator(`[aria-label^="Open order ${ORD}"]`).first().click(); await cash.waitForTimeout(3000);
await cash.locator("[data-testid=drawer-full-menu]").click(); await cash.waitForTimeout(4500);
const banner = await cash.evaluate(() => (document.body.innerText||"").replace(/\s+/g," ").slice(0,600));
log("  after Full Menu, screen says:", banner.slice(0,420));
const search = cash.locator('input[placeholder*="Search menu" i]').first();
await search.fill("Audit Item 60568"); await cash.waitForTimeout(2000);
await cash.locator('[data-testid="menu-grid"] button[aria-pressed]').first().click(); await cash.waitForTimeout(2000);
const opt = cash.locator('[data-testid^="modifier-option-"]').filter({ hasText: /Rare|Well done/ }).first();
await opt.click(); await cash.waitForTimeout(600);
await cash.locator("[data-testid=modifier-dialog-add]").click(); await cash.waitForTimeout(2000);
await shot(cash, "11c-fullmenu-added");
const panel = await cash.evaluate(() => (document.querySelector("[data-testid=order-panel]")?.innerText ?? document.body.innerText).replace(/\s+/g," ").slice(0,700));
log("  panel now:", panel.slice(0,500));
const btns = await cash.evaluate(() => Array.from(document.querySelectorAll("button")).map(b=>b.textContent.trim()).filter(Boolean).slice(-12));
log("  buttons:", JSON.stringify(btns));
const send = cash.getByRole("button", { name: /send new items|send to kitchen/i });
log("  send control:", await send.count(), await send.first().textContent().catch(()=>null));
if (await send.count()) { await send.first().click(); await cash.waitForTimeout(6000); }
await shot(cash, "11d-fullmenu-sent");
const after = await apiGet(cash, `/api/v1/pos/orders?branchId=${S.branchId}&size=5`);
const rows = after.body?.data?.content ?? after.body?.data ?? [];
log("  latest orders:", JSON.stringify(rows.slice(0,3).map(r=>({no:r.orderNo,q:r.itemQuantity,total:r.totalPaisa,st:r.settlementStatus}))));
saveState({ fullMenuLands: { rows: rows.slice(0,3) } });
await browser.close();
