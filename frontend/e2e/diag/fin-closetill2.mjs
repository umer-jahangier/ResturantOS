import { chromium } from "@playwright/test";
import { PERSONAS, login, shot, save, visit } from "./fin-lib.mjs";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1500, height: 1400 } });
const page = await ctx.newPage();
await login(page, PERSONAS.cashier);
await visit(page, "/app/pos", { tries: 1, settle: 8000 });
const before = await page.locator("body").innerText();
await page.locator("button", { hasText: /close till/i }).first().click();
await page.waitForTimeout(7000);
const after = await page.locator("body").innerText();
const newLines = after.split("\n").filter((l) => !before.includes(l.trim()) && l.trim());
console.log("=== TEXT THAT APPEARED AFTER CLICKING CLOSE TILL ===");
console.log(newLines.join("\n"));
const ctrls = await page.evaluate(() => [...document.querySelectorAll("input,select,textarea,button")].map((e)=>`${e.tagName}<${e.getAttribute("type")||""}>[${e.getAttribute("name")||e.getAttribute("placeholder")||e.getAttribute("aria-label")||e.textContent?.trim().slice(0,30)}]`));
console.log("\n=== CONTROLS ON PAGE ===");
console.log(JSON.stringify(ctrls, null, 1));
await shot(page, "closetill-inline-panel");
save("closetill2.txt", newLines.join("\n") + "\n\nCONTROLS:\n" + JSON.stringify(ctrls, null, 1));
await browser.close();
